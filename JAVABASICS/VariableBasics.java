public class VariableBasics {
    public static void main(String[] args) {
        int a = 5;
        System.out.println(a);
        int b;
        b = 10;
        System.out.println(b);
        int x = 8;
        System.out.println(x);
        x = x - 2;
        System.out.println(x);
        x = x + 20;
        System.out.println(x);
        x = x * 5;
        System.out.println(x);
        x = x / 2;
        System.out.println(x);
        
    }
    
}
