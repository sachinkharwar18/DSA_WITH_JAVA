public class ArithmeticOperation {
    public static void main(String[] args) {
        int x = 6 , y = 3;
        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(x*y);
        System.out.println(x/y);

        double a = 50;
        double b = 8;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
    }
    
}
